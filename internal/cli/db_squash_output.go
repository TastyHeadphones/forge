// File: internal/cli/db_squash_output.go
//
// What `forge db squash` writes around the dump: the baseline's header, and
// the next steps it prints.
//
// THE HEADER IS A FUNCTION OF THE SQUASHED HISTORY AND NOTHING ELSE. It used
// to carry the wall-clock time and the absolute --from-dir path, so a second
// squash of the same history never reproduced the file byte for byte, and a
// reviewer could not tell "re-cut" from "changed". reliant stripped it with
// `tail -n +6`. What a reader needs to know about where the baseline came
// from is stable: which migrations it replaces. So the header names their
// count and version range, and the dump flags; the body is pg_dump's, which
// is deterministic for one history and one image (squashBaseline drops the
// one random part, `\restrict <key>`).

package cli

import (
	"fmt"
	"io"

	"github.com/reliant-labs/forge/pkg/migratekit/compat"
)

// squashHeader is the comment a squashed baseline opens with.
func squashHeader(squashed []compat.Migration) string {
	from := "no migrations"
	switch n := len(squashed); n {
	case 0:
	case 1:
		from = fmt.Sprintf("1 migration, %d", squashed[0].Version)
	default:
		from = fmt.Sprintf("%d migrations, %d through %d", n, squashed[0].Version, squashed[n-1].Version)
	}
	return "-- Generated by `forge db squash` from " + from + ".\n" +
		"-- pg_dump --no-owner --no-privileges --inserts --exclude-table=public.schema_migrations --exclude-table=public.schema_migrations_compat --exclude-table=public.schema_migrations_applied\n" +
		"-- pg_dump's session prelude (SET, set_config) and psql meta-commands (\\restrict) are stripped.\n\n"
}

// printSquashNextSteps tells the user what to do with the baseline.
//
// It used to end with "`forge db migrate force <id>` against any pre-existing
// databases so they accept the new baseline". That is unsafe advice: force
// records a version as applied without checking anything, so it would mark a
// baseline applied on a database whose schema is not the one the baseline
// builds, and skip the verification adoption exists to do. A database the
// squashed migrations built cannot take this baseline at all — forge adopts
// only a history ANOTHER tool recorded (`-- forge:adopts`) — so the steps say
// that, say what `migrate up` does there (refuses, whatever the baseline's
// number: TestSquashNextStepsClaimsHoldAgainstTheMigrator), and point at the
// preview.
func printSquashNextSteps(w io.Writer, fromDir string) {
	_, _ = fmt.Fprintln(w, "\nNext steps:")
	_, _ = fmt.Fprintln(w, "  1. Review the baseline: it should hold what the squashed migrations built (their schema, and")
	_, _ = fmt.Fprintln(w, "     the rows they inserted) and nothing an application wrote.")
	_, _ = fmt.Fprintf(w, "  2. Replace the squashed migrations with it: move them out of %s (git keeps them).\n", fromDir)
	_, _ = fmt.Fprintln(w, "  3. A database the squashed migrations already built cannot take this baseline: forge adopts")
	_, _ = fmt.Fprintln(w, "     only a history another tool recorded (`-- forge:adopts`, see the forge skill")
	_, _ = fmt.Fprintln(w, "     db/deploy-migrations). `forge db migrate up` refuses such a database, since it holds")
	_, _ = fmt.Fprintln(w, "     versions this release no longer carries, and changes nothing. Squash this history only if")
	_, _ = fmt.Fprintln(w, "     every database it built can be rebuilt.")
	_, _ = fmt.Fprintln(w, "  4. Preview every database before it meets this release: `forge db migrate status --dsn <dsn>`,")
	_, _ = fmt.Fprintln(w, "     then `forge db migrate up --dsn <dsn>` against a copy. A fresh database applies the baseline.")
	_, _ = fmt.Fprintln(w, "     Never `forge db migrate force` the baseline onto a database: force records it as applied")
	_, _ = fmt.Fprintln(w, "     without checking that the schema is the one it builds.")
}
